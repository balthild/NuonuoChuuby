#!/bin/sh
#
# Generate the asset manifest the app compiles in: the pinned upstream commit and
# the list of runtime files it downloads on a release build.
#
#   Tools/generate-asset-manifest.sh <upstream-repo> <output-swift>
#
# The output is Swift source (`Asset/AssetManifest.swift`, git-ignored and
# regenerated on every build), so a release build needs no manifest file at
# runtime and the pinned commit travels in the binary. It still contains only
# paths and a commit id — no asset bytes, nothing that needs a redistribution
# grant.
#
# The file is only rewritten when its content changes, so an unchanged submodule
# does not force the module to recompile on every build.
set -eu

here=$(dirname "$0")
src=${1:?usage: generate-asset-manifest.sh <upstream-repo> <output-swift>}
out=${2:?usage: generate-asset-manifest.sh <upstream-repo> <output-swift>}

commit=$(git -C "$src" rev-parse HEAD)
upstream=$(git -C "$src" config --get remote.origin.url | sed 's/\.git$//')

files=$(mktemp "${TMPDIR:-/tmp}/nuonuo-manifest-files.XXXXXX")
work=$(mktemp "${TMPDIR:-/tmp}/nuonuo-manifest.XXXXXX")
trap 'rm -f "$files" "$work"' EXIT HUP INT TERM

"$here/asset-files.sh" "$src" > "$files"

# Escape a shell string for a Swift string literal.
swift_string() {
	printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
}

total=0
{
	printf '%s\n' '// Generated by Tools/generate-asset-manifest.sh — do not edit.' ''
	printf '%s\n' 'extension AssetManifest {'
	printf '%s\n' '	static let bundled = AssetManifest('
	printf '\t\tupstream: %s,\n' "$(swift_string "$upstream")"
	printf '\t\tcommit: %s,\n' "$(swift_string "$commit")"
	printf '%s\n' '		files: ['
	while IFS="$(printf '\t')" read -r destination source; do
		total=$((total + 1))
		printf '\t\t\t.init(path: %s, source: %s),\n' \
			"$(swift_string "$destination")" "$(swift_string "$source")"
	done < "$files"
	printf '%s\n' '		]' '	)' '}'
} > "$work"

if cmp -s "$work" "$out"; then
	rm -f "$work"
else
	mkdir -p "$(dirname "$out")"
	mv "$work" "$out"
	chmod 644 "$out"
fi

printf '%s\n' "Wrote $out" "  commit: $commit" "  files:  $total"
